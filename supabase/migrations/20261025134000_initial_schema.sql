create extension if not exists pgcrypto with schema extensions;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  role text not null default 'driver' check (role in ('driver', 'admin')),
  license_plate text,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create table public.facilities (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);

create table public.facility_config (
  facility_id uuid primary key references public.facilities (id) on delete cascade,
  total_power_kw numeric(6, 2) not null default 7 check (total_power_kw > 0),
  per_bay_max_power_kw numeric(6, 2) not null default 7 check (per_bay_max_power_kw > 0),
  default_battery_capacity_kwh numeric(7, 2) not null default 30 check (default_battery_capacity_kwh > 0),
  consumption_kwh_per_km numeric(6, 3) not null default 0.18 check (consumption_kwh_per_km > 0),
  safety_margin_percent numeric(5, 2) not null default 10 check (safety_margin_percent between 0 and 100),
  updated_at timestamptz not null default now()
);

create table public.bays (
  id bigint generated by default as identity primary key,
  facility_id uuid not null references public.facilities (id) on delete cascade,
  name text not null,
  max_power_kw numeric(6, 2) not null default 7 check (max_power_kw > 0),
  created_at timestamptz not null default now(),
  unique (facility_id, name)
);

create table public.ev_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  facility_id uuid not null references public.facilities (id) on delete cascade,
  bay_id bigint references public.bays (id) on delete set null,
  driver_name text not null,
  license_plate text not null,
  vehicle_model text not null,
  battery_capacity_kwh numeric(7, 2) not null check (battery_capacity_kwh > 0),
  current_charge_percent numeric(5, 2) not null check (current_charge_percent between 0 and 100),
  target_charge_percent numeric(5, 2) not null check (target_charge_percent between 0 and 100),
  trip_distance_km numeric(8, 2) not null default 0 check (trip_distance_km >= 0),
  arrival_time timestamptz not null default now(),
  departure_time timestamptz not null,
  status text not null default 'WAITING'
    check (status in ('WAITING', 'CHARGING', 'COMPLETED', 'DEPARTED')),
  queue_position integer check (queue_position is null or queue_position > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (departure_time > arrival_time)
);

create unique index ev_sessions_one_active_vehicle_per_bay
  on public.ev_sessions (bay_id)
  where bay_id is not null and status <> 'DEPARTED';

create index ev_sessions_user_created_at on public.ev_sessions (user_id, created_at desc);
create index ev_sessions_facility_status on public.ev_sessions (facility_id, status, queue_position);

