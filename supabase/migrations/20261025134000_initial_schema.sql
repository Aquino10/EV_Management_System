create or replace function public.is_facility_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.facilities enable row level security;
alter table public.facility_config enable row level security;
alter table public.bays enable row level security;
alter table public.ev_sessions enable row level security;

revoke all on public.profiles, public.facilities, public.facility_config, public.bays, public.ev_sessions from anon;
grant select on public.profiles, public.facilities, public.facility_config, public.bays, public.ev_sessions to authenticated;
grant update (display_name, license_plate) on public.profiles to authenticated;
grant insert, update, delete on public.facility_config, public.bays, public.ev_sessions to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "Users can read their own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_facility_admin()));

create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "Authenticated users can read facilities"
  on public.facilities for select to authenticated
  using (true);

create policy "Admins can manage facilities"
  on public.facilities for all to authenticated
  using ((select public.is_facility_admin()))
  with check ((select public.is_facility_admin()));

create policy "Authenticated users can read facility settings"
  on public.facility_config for select to authenticated
  using (true);

create policy "Admins can manage facility settings"
  on public.facility_config for all to authenticated
  using ((select public.is_facility_admin()))
  with check ((select public.is_facility_admin()));

create policy "Authenticated users can read bays"
  on public.bays for select to authenticated
  using (true);

create policy "Admins can manage bays"
  on public.bays for all to authenticated
  using ((select public.is_facility_admin()))
  with check ((select public.is_facility_admin()));

create policy "Users can read their sessions and admins can read all"
  on public.ev_sessions for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_facility_admin()));

create policy "Users can create their own waiting sessions"
  on public.ev_sessions for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and status = 'WAITING'
    and bay_id is null
  );

create policy "Admins can manage all sessions"
  on public.ev_sessions for all to authenticated
  using ((select public.is_facility_admin()))
  with check ((select public.is_facility_admin()));
